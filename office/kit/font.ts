// tlon's own bitmap fonts, ASCII 32..126, in two cuts of one design: `SMALL` (6×9: capitals 5×7,
// x-height 5, 2 rows of descender) and `BODY` (7×13: capitals 5×9, ascenders a row taller, x-height
// 6, 3 rows of descender). Glyphs are rows of "#" ink from the top; the rightmost column(s) are
// always blank, the spacing. Legibility first: I l 1 | and 0 O o, 5 S, 8 B, rn m are each told
// apart by shape, apertures stay open; corners are clipped round for warmth.
export type Cut = { w: number; h: number; ascent: number; glyph: (ch: string) => number[] }

function cut(w: number, h: number, ascent: number, glyphs: Record<string, string[]>): Cut {
  const bits = new Map(Object.entries(glyphs).map(([ch, rows]) => [ch, Array.from({ length: h }, (_, r) =>
    parseInt((rows[r] ?? "").padEnd(w, ".").replace(/\./g, "0").replace(/#/g, "1"), 2))]))
  /** the rows of `ch` (an unknown char draws as "?"), bit `w-1` the leftmost column */
  return { w, h, ascent, glyph: (ch) => bits.get(ch) ?? bits.get("?")! }
}

